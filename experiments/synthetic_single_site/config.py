"""
Experiment: synthetic_single_site
==================================
Single-site RWMH calibration on synthetically generated NEE observations.

This is a pipeline test; data are not real flux-tower observations. We run
SIPNET at known ("ground-truth") parameter values to generate synthetic NEE,
add Gaussian noise, then calibrate and check recovery.

Directory layout
----------------
data/
    climate.clim    — 3-year ERA5-derived climate slice (generated by setup_data)
    obs_nee.npy     — synthetic noisy NEE timeseries (generated by setup_data)
outputs/
    mcmc/<run_id>.nc — ArviZ NetCDF MCMC outputs (generated by run_mcmc.py)

Usage
-----
Generate data:
    python config.py

Run MCMC:
    python run_mcmc.py --run_id rwmh_v1

Explore results in notebooks/:
    notebooks/01_prior_predictive.ipynb
    notebooks/02_mcmc_diagnostics.ipynb
"""
from __future__ import annotations

from pathlib import Path

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
EXPERIMENT_DIR = Path(__file__).parent
DATA_DIR = EXPERIMENT_DIR / "data"
OUTPUT_DIR = EXPERIMENT_DIR / "outputs"
RAW_CLIMATE = EXPERIMENT_DIR.parent.parent / "data" / "era5_site1.clim"

# ---------------------------------------------------------------------------
# Experiment parameters
# ---------------------------------------------------------------------------
GROUND_TRUTH: dict[str, float] = {
    "a_max":          120.0,
    "psn_t_opt":       20.0,
    "half_sat_par":   200.0,
    "base_veg_resp":    0.5,
    "veg_resp_q10":     2.0,
    "base_soil_resp":   0.3,
    "soil_resp_q10":    2.2,
    "wue_const":       10.0,
}

SIGMA_OBS: float = 2.0   # gC m-2 per 3-hr timestep; includes model structural error

CLIMATE_N_YEARS: int = 3  # length of climate slice used for calibration

MCMC_KWARGS: dict = dict(
    method="tfp_rwmh",
    num_results=2000,
    num_warmup=1000,
    step_size=0.01,
    num_chains=2,
)


# ---------------------------------------------------------------------------
# Prior
# ---------------------------------------------------------------------------

def build_prior() -> "ProductDistribution":
    """Independent log-normal / normal priors over calibrated parameters.

    Written directly in ProbPipe so the prior is fully inspectable and can
    be extended to correlated priors later. The prior is the sole source of
    truth for which parameters are being calibrated and what their names are.
    """
    import jax.numpy as jnp
    from probpipe import ProductDistribution, LogNormal, Normal

    return ProductDistribution(
        a_max          = LogNormal(jnp.log(120.0), 0.5,  name="a_max"),
        psn_t_opt      = Normal(20.0,  8.0,               name="psn_t_opt"),
        half_sat_par   = LogNormal(jnp.log(200.0), 0.5,  name="half_sat_par"),
        base_veg_resp  = LogNormal(jnp.log(0.5),   0.5,  name="base_veg_resp"),
        veg_resp_q10   = LogNormal(jnp.log(2.0),   0.3,  name="veg_resp_q10"),
        base_soil_resp = LogNormal(jnp.log(0.3),   0.5,  name="base_soil_resp"),
        soil_resp_q10  = LogNormal(jnp.log(2.2),   0.3,  name="soil_resp_q10"),
        wue_const      = LogNormal(jnp.log(10.0),  0.5,  name="wue_const"),
    )


# ---------------------------------------------------------------------------
# Data setup
# ---------------------------------------------------------------------------

def setup_data() -> None:
    """Write climate slice and synthetic observations to data/. Overwrites.

    Steps
    -----
    1. Read era5_site1.clim and slice to CLIMATE_N_YEARS.
    2. Run SIPNET at GROUND_TRUTH parameters.
    3. Add iid Gaussian noise (std = SIGMA_OBS).
    4. Save climate.clim and obs_nee.npy to DATA_DIR.
    """
    import numpy as np
    from pysipnet import SIPNETRunner, SIPNETModel
    from pysipnet.climate import ClimateDrivers
    from pysipnet.runner import ClimateStaging

    DATA_DIR.mkdir(parents=True, exist_ok=True)

    # --- Slice climate ---
    # Read raw lines and write a subset (ClimateDrivers has no slice/write API)
    with open(str(RAW_CLIMATE)) as f:
        all_lines = f.readlines()
    n_steps = int(CLIMATE_N_YEARS * 365 * 8)  # 8 three-hour steps per day
    n_steps = min(n_steps, len(all_lines))

    climate_path = DATA_DIR / "climate.clim"
    climate_path.write_text("".join(all_lines[:n_steps]))
    print(f"  Climate slice: {n_steps} timesteps → {climate_path}")

    # --- Run SIPNET at ground-truth parameters ---
    from sipnet_calibration import default_base_params

    runner = SIPNETRunner(climate_staging=ClimateStaging.SYMLINK)
    base_params = default_base_params()
    climate = ClimateDrivers.from_path(str(climate_path))
    model = SIPNETModel(runner, base_params=base_params, base_climate=climate)

    result = model(**GROUND_TRUTH)
    true_nee = result.nee().values

    # --- Add noise ---
    rng = np.random.default_rng(0)
    obs_nee = true_nee + rng.normal(0.0, SIGMA_OBS, size=len(true_nee))

    obs_path = DATA_DIR / "obs_nee.npy"
    np.save(str(obs_path), obs_nee)
    print(f"  Synthetic NEE:  {len(obs_nee)} timesteps → {obs_path}")


# ---------------------------------------------------------------------------
# Model / data loader  (used by run_mcmc.py and notebooks)
# ---------------------------------------------------------------------------

def load_model() -> "tuple[SimpleModel, np.ndarray]":
    """Read data/ and return (SimpleModel, obs_nee) ready for condition_on.

    Returns
    -------
    model:
        ProbPipe SimpleModel wrapping SingleSiteGaussianLikelihood.
    obs_nee:
        Observed (synthetic) NEE timeseries as a numpy array.

    Usage
    -----
        model, obs_nee = load_model()
        posterior = condition_on(model, obs_nee, **MCMC_KWARGS)
    """
    import numpy as np
    from probpipe import SimpleModel
    from pysipnet import SIPNETRunner, SIPNETModel
    from pysipnet.climate import ClimateDrivers
    from pysipnet.runner import ClimateStaging
    from sipnet_calibration import SingleSiteGaussianLikelihood, default_base_params

    climate_path = DATA_DIR / "climate.clim"
    obs_path = DATA_DIR / "obs_nee.npy"

    if not climate_path.exists() or not obs_path.exists():
        raise FileNotFoundError(
            f"Data not found in {DATA_DIR}. Run `python config.py` first."
        )

    obs_nee = np.load(str(obs_path))

    runner = SIPNETRunner(climate_staging=ClimateStaging.SYMLINK)
    base_params = default_base_params()
    climate = ClimateDrivers.from_path(str(climate_path))
    sipnet_model = SIPNETModel(runner, base_params=base_params, base_climate=climate)

    prior = build_prior()
    likelihood = SingleSiteGaussianLikelihood(
        prior=prior,
        model=sipnet_model,
        sigma_obs=SIGMA_OBS,
        output="nee",
    )
    model = SimpleModel(prior, likelihood)
    return model, obs_nee


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

if __name__ == "__main__":
    print("Setting up synthetic_single_site data...")
    setup_data()
    print("Done.")
